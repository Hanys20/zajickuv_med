import { readFileSync, writeFileSync } from 'node:fs';

// Preserve the original artwork as small, static SVGs. HTML image transforms
// can run on the compositor instead of repainting SVG geometry each frame.
const source = readFileSync(new URL('../public/images/logo/entrance-animation.svg', import.meta.url), 'utf8');
const element = (id) => {
  const match = source.match(new RegExp(`<([a-z]+)\\b[^>]*\\bid="${id}"[^>]*(?:/>|>[\\s\\S]*?</\\1>)`));
  if (!match) throw new Error(`Missing logo part: ${id}`);
  return match[0].replace(/\s(?:id|class|aria-hidden)="[^"]*"/g, '');
};

// Cropped boxes with padding keep GPU layers small even at high pixel density.
const layers = [
  ['ear-left', [18, 10, 31, 62], element('ear-left'), '50% 98%'],
  ['ear-right', [52, 10, 32, 62], element('ear-right'), '50% 98%'],
  ['honey', [25.72, 77.91, 49.42, 59.62], element('honey-fill'), '50% 100%'],
  ['whiskers-left', [12, 107, 30, 11], element('whiskers-left'), '96% 50%'],
  ['whiskers-right', [59, 107, 30, 11], element('whiskers-right'), '4% 50%'],
  ['jar', [22, 71, 57, 70], element('jar-outline') + element('lid'), '50% 50%'],
  ['sides', [22, 106, 57, 9], element('jar-temporary-sides'), '50% 50%'],
  ['nose', [43, 106, 15, 14], element('nose'), '50% 50%'],
];

const output = `// Generated by node scripts/generate-intro-logo.mjs from the original logo.
// Static cropped SVGs: animate their HTML image layers, never SVG geometry.
function layer(name: string, box: number[], artwork: string, transformOrigin: string) {
  const [x, y, width, height] = box;
  const svg = \`<svg xmlns="http://www.w3.org/2000/svg" viewBox="\${box.join(' ')}" fill="\${name === 'honey' ? '#f3a738' : '#1d1d1b'}">\${artwork}</svg>\`;
  return {
    name,
    src: 'data:image/svg+xml,' + encodeURIComponent(svg),
    style: {
      left: \`\${(x / 103.6) * 100}%\`,
      top: \`\${(y / 152.34) * 100}%\`,
      width: \`\${(width / 103.6) * 100}%\`,
      height: \`\${(height / 152.34) * 100}%\`,
      transformOrigin,
    },
  };
}

export const INTRO_LOGO_LAYERS = [
${layers.map(([name, box, artwork, origin]) => `  layer(${JSON.stringify(name)}, ${JSON.stringify(box)}, ${JSON.stringify(artwork)}, ${JSON.stringify(origin)}),`).join('\n')}
];
`;
writeFileSync(new URL('../src/lib/introLogo.ts', import.meta.url), output);
